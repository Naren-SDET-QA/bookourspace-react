import { readdir, readFile, mkdir, writeFile, stat } from 'node:fs/promises';
import path from 'node:path';
import dotenv from 'dotenv';

const files = async (directory: string): Promise<string[]> => {
  const entries = await readdir(directory, { withFileTypes: true });
  const nested = await Promise.all(entries.map(entry => entry.isDirectory() ? files(path.join(directory, entry.name)) : [path.join(directory, entry.name)]));
  return nested.flat();
};
const components = [];
for (const file of (await files('src/components')).filter(file => file.endsWith('.tsx')).sort()) {
  const text = await readFile(file, 'utf8');
  components.push({ file, lines: text.split('\n').length, handlers: [...text.matchAll(/\b(onClick|onSubmit|onChange)=/g)].length, browserStorage: /localStorage|sessionStorage/.test(text), simulationSignals: /simulat|mock|Math\.random|setTimeout/.test(text) });
}
const api = [];
for (const file of ['server.ts', 'src/server/movieRoutes.ts']) {
  const text = await readFile(file, 'utf8');
  for (const match of text.matchAll(/\b(app|router)\.(get|post|put|patch|delete)\(([^\n]+)/g)) {
    const route = match[3].match(/['"]([^'"]+)['"]/)?.[1];
    if (route) api.push({ method: match[2].toUpperCase(), route, file, line: text.slice(0, match.index).split('\n').length });
  }
}
const sqlTables = new Set<string>();
for (const file of (await files('supabase')).filter(file => file.endsWith('.sql') && !file.includes('tests'))) {
  const text = await readFile(file, 'utf8');
  for (const match of text.matchAll(/create table\s+(?:if not exists\s+)?([\w.]+)/gi)) sqlTables.add(match[1]);
}
const publicAssets = [];
for (const file of await files('public')) publicAssets.push({ file, bytes: (await stat(file)).size });
const environment = dotenv.parse(await readFile('.env.local', 'utf8').catch(() => ''));
const privateNames = Object.keys(environment).filter(name => /SECRET|SERVICE_ROLE|PASSWORD|PRIVATE_KEY/.test(name));
const bundleSecretHits: Array<{ file: string; variableName: string }> = [];
for (const file of (await files('dist')).filter(file => /\.(js|html|css)$/.test(file))) {
  const text = await readFile(file, 'utf8');
  for (const name of privateNames) if (environment[name].length > 8 && text.includes(environment[name])) bundleSecretHits.push({ file, variableName: name });
}
const summary = { componentCount: components.length, sourceInteractiveHandlers: components.reduce((sum, row) => sum + row.handlers, 0), apiRouteCount: api.length, sqlTables: [...sqlTables], publicAssetBytes: publicAssets.reduce((sum, file) => sum + file.bytes, 0), largestAssets: publicAssets.sort((a, b) => b.bytes - a.bytes).slice(0, 8), bundleSecretHits };
await mkdir('output/audit', { recursive: true });
await writeFile('output/audit/source-inventory.json', JSON.stringify({ summary, components, api }, null, 2));
const markdown = `# Source inventory — 2026-11-02\n\nGenerated by scripts/audit-inventory.ts. Handler counts identify review scope; they do not prove that an interaction works. Simulation signals are inspection hints, not automatic findings.\n\n## Components\n\n| File | Lines | Interactive handlers | Storage signal | Simulation/timer signal |\n|---|---:|---:|---|---|\n${components.map(row => `| ${row.file.replaceAll('\\', '/')} | ${row.lines} | ${row.handlers} | ${row.browserStorage} | ${row.simulationSignals} |`).join('\n')}\n\n## HTTP routes\n\n| Method | Route | Location |\n|---|---|---|\n${api.map(row => `| ${row.method} | ${row.route} | ${row.file}:${row.line} |`).join('\n')}\n\n## Tables declared locally\n\n${[...sqlTables].sort().map(table => `- ${table}`).join('\n')}\n`;
await writeFile('output/audit/SOURCE_INVENTORY.md', markdown);
console.log(JSON.stringify(summary, null, 2));
