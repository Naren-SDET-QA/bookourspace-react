export function transliterateLatinToScript(input: string, lang: AppLanguage): string {
  if (!input || lang === 'en') return input;
  const map = latinDigraphMap[lang] || latinDigraphMap.te;
  let result = '';
  const lower = input.toLowerCase();
  let i = 0;
  while (i < lower.length) {
    if (i + 1 < lower.length) {
      const two = lower.slice(i, i + 2);
      if (map[two]) {
        result += map[two];
        i += 2;
        continue;
      }
    }
    const ch = lower[i];
    if (map[ch]) {
      result += map[ch];
    } else {
      result += input[i];
    }
    i++;
  }
  return result;
}

export function localizeAreaName(area: string, lang: AppLanguage): string {
  if (!area) return '';
  if (lang === 'en') return area;
  const entry = localityTranslations[area];
  if (entry) {
    if (lang === 'te') return entry.te;
    if (lang === 'hi' || lang === 'mr') return entry.hi;
    if (lang === 'ta' && entry.ta) return entry.ta;
    if (lang === 'kn' && entry.kn) return entry.kn;
  }
  // Check partial locality match (e.g. "Ameerpet, Hyderabad")
  let localized = area;
  for (const [enKey, val] of Object.entries(localityTranslations)) {
    const replacement =
      lang === 'te'
        ? val.te
        : lang === 'hi' || lang === 'mr'
        ? val.hi
        : lang === 'ta' && val.ta
        ? val.ta
        : lang === 'kn' && val.kn
        ? val.kn
        : transliterateLatinToScript(enKey, lang);
    localized = localized.replace(new RegExp(enKey.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'), 'gi'), replacement);
  }
  if (/[a-zA-Z]/.test(localized)) {
    return transliterateLatinToScript(localized, lang);
  }
  return localized;
}

export function ensureChosenLanguageText(
  item:
    | string
    | { en?: string; te?: string; hi?: string; name?: string; nameTe?: string; nameHi?: string },
  lang: AppLanguage
): string {
  if (typeof item === 'string') {
    if (lang === 'en') return item;
    // Preserve brand name BookOurSpace / BOS in English
    return item
      .split(/(BookOurSpace|BOS)/g)
      .map((part) =>
        part === 'BookOurSpace' || part === 'BOS'
          ? part
          : transliterateLatinToScript(part, lang)
      )
      .join('');
  }

  const enText = item.en || item.name || '';
  const teText = item.te || item.nameTe || '';
  const hiText = item.hi || item.nameHi || '';

  if (lang === 'en') {
    return enText || teText;
  }
  if (lang === 'te') {
    if (teText && !/[a-zA-Z]/.test(teText)) return teText;
    if (teText) return teText.replace(/\s*\([A-Za-z0-9\s/&,-]+\)/g, '').trim() || transliterateLatinToScript(enText, 'te');
    return transliterateLatinToScript(enText, 'te');
  }
  if (lang === 'hi' || lang === 'mr') {
    if (hiText && !/[a-zA-Z]/.test(hiText)) return hiText;
    if (hiText) return hiText.replace(/\s*\([A-Za-z0-9\s/&,-]+\)/g, '').trim() || transliterateLatinToScript(enText, lang);
    return transliterateLatinToScript(enText, lang);
  }
  return transliterateLatinToScript(enText, lang);
}
